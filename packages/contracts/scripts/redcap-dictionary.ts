import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { buildSurgicalDictionary } from "#scripts/dictionary";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const output = fileURLToPath(new URL("../src/redcap-schema.ts", import.meta.url));
const raw = execFileSync(
  `${root}.local/redcap-venv/bin/python`,
  [
    "tools/redcap/server.py",
    "data_dictionary",
    "--args",
    JSON.stringify({ forms: ["surgery_c61", "surgery_c61_resected_lesion"] }),
  ],
  { cwd: root, encoding: "utf8" },
);
const { fields, regions } = buildSurgicalDictionary(JSON.parse(raw));
await writeFile(
  output,
  `// Generated by scripts/redcap-dictionary.ts from REDCap project 64. Do not edit.
export const redcapAllSegmentRegions = ${JSON.stringify(regions, null, 2)} as const;

export const redcapSurgicalFields = ${JSON.stringify(fields, null, 2)} as const;
`,
);
execFileSync("pnpm", ["exec", "prettier", "--write", output], { cwd: root, stdio: "inherit" });
